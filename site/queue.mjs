// Reads the verification queue, checks every entry against the format in
// Verification/README.md, and writes Verification/_Gaps.md: everything still
// open, partial or pending, by node and by the work that would close it.
//
//   node site/queue.mjs            write _Gaps.md
//   node site/queue.mjs --check    write nothing; fail on a broken entry, warn
//                                  when _Gaps.md is out of date
//
// A failure is an entry the gap list cannot read, or one that names a node
// the vault does not have. A warning is work left over on a gap: not tried by
// clear-queue yet, no kind, or nothing named that would close it.

import { access, readFile, readdir, writeFile } from "node:fs/promises"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const queueDir = join(repoRoot, "Verification")
const vaultDir = join(repoRoot, "Theology")
export const GAPS_FILE = "_Gaps.md"

export const STATUSES = ["open", "partial", "pending", "confirmed", "corrected", "unresolvable"]
export const KINDS = ["metadata", "copy", "page", "content", "lead", "unchecked"]
// The gaps, in the order a reader should act on them: a known error first.
export const GAPS = ["pending", "partial", "open"]
const REQUIRED = ["Status", "Node", "Source", "What is open"]

// Entries start at a "### V<n>." heading. The preamble and the run record come
// before the first one; a field runs on over following lines until the next
// field, a rule or a heading.
export const parseQueue = (text, file) => {
  const entries = []
  let entry = null
  let field = null
  for (const line of text.split(/\r?\n/)) {
    const head = line.match(/^### (V\d+)\.\s+(.*)$/)
    if (head) {
      entry = { file, id: head[1], title: head[2].trim(), fields: {} }
      entries.push(entry)
      field = null
      continue
    }
    if (!entry) continue
    if (/^(---|#)/.test(line)) {
      field = null
      if (line.startsWith("#")) entry = null
      continue
    }
    const f = line.match(/^\*\*([A-Za-z ]+):\*\*\s?(.*)$/)
    if (f) {
      field = f[1]
      entry.fields[field] = f[2].trim()
    } else if (field && line.trim()) {
      entry.fields[field] += `\n${line.trim()}`
    }
  }
  return entries
}

// The nodes an entry names, as vault paths: every `Folder/Title` in backticks.
export const nodesOf = (entry) => [...(entry.fields.Node ?? "").matchAll(/`([^`/]+\/[^`]+)`/g)].map((m) => m[1])

export const lintEntry = (entry, nodeExists = () => true) => {
  const fails = []
  const warns = []
  const f = entry.fields
  for (const name of REQUIRED) if (!f[name]) fails.push(`no ${name}`)
  if (f.Status && !STATUSES.includes(f.Status)) fails.push(`status "${f.Status}" is not one of ${STATUSES.join(", ")}`)
  if (f.Kind && !KINDS.includes(f.Kind)) fails.push(`kind "${f.Kind}" is not one of ${KINDS.join(", ")}`)
  if (f.Node && !nodesOf(entry).length) fails.push("Node names no `Folder/Title` path")
  for (const node of nodesOf(entry)) if (!nodeExists(node)) fails.push(`node ${node} matches no note`)
  // A settled entry needs neither: nothing is left to route or to fetch.
  if (GAPS.includes(f.Status)) {
    if (!f.Kind) warns.push("no kind")
    if (!f.Tried) warns.push("never tried")
    else if (f.Status !== "pending" && !f.Needs) warns.push("a gap with no Needs")
  }
  return { fails, warns }
}

// GitHub's heading anchors: lower case, punctuation dropped, each space a hyphen.
export const anchor = (heading) =>
  heading
    .toLowerCase()
    .trim()
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .replace(/\s/g, "-")

const href = (file, entry) => {
  const path = encodeURIComponent(file).replace(/\(/g, "%28").replace(/\)/g, "%29")
  return entry ? `${path}#${anchor(`${entry.id}. ${entry.title}`)}` : path
}
const nodeName = (file) => file.replace(/\.md$/, "")
const byId = (a, b) => Number(a.id.slice(1)) - Number(b.id.slice(1))
const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`

export const renderGaps = (entries) => {
  const gaps = entries.filter((e) => GAPS.includes(e.fields.Status))
  const closed = entries.length - gaps.length
  const count = (status) => gaps.filter((e) => e.fields.Status === status).length
  const files = [...new Set(gaps.map((e) => e.file))].sort()
  const untried = entries.filter((e) => !e.fields.Tried && GAPS.includes(e.fields.Status))

  const out = [
    "# Gaps",
    "",
    "Generated by `npm run queue` from the entries in this folder. Do not edit it by hand: change the entry and run the script again.",
    "",
    `What the pipeline could not confirm in full, across ${plural(files.length, "node")}: ${count("pending")} pending, ${count("partial")} partial, ${count("open")} open. ${closed} closed. Each line links to its entry, which says what is still missing and what was tried. The statuses and kinds are explained in [README.md](README.md).`,
    "",
  ]
  if (untried.length) {
    out.push(`${plural(untried.length, "gap")} ${untried.length === 1 ? "has" : "have"} not had the clear-queue attempt yet, so ${untried.length === 1 ? "it is" : "they are"} wider than ${untried.length === 1 ? "it needs" : "they need"} to be.`, "")
  }

  out.push("## By node", "")
  for (const file of files) {
    out.push(`### [${nodeName(file)}](${href(file)})`, "")
    const mine = gaps.filter((e) => e.file === file)
    mine.sort((a, b) => GAPS.indexOf(a.fields.Status) - GAPS.indexOf(b.fields.Status) || byId(a, b))
    for (const e of mine) {
      const kind = e.fields.Kind ? `, ${e.fields.Kind}` : ""
      const tried = e.fields.Tried ? "" : ", not tried yet"
      out.push(`- [${e.id}](${href(file, e)}) ${e.fields.Status}${kind}${tried}. ${e.title}`)
    }
    out.push("")
  }

  out.push("## By what would close them", "")
  out.push("Grouped by the entry's **Needs**. One copy of a work closes every gap under it.", "")
  const needs = new Map()
  for (const e of gaps) {
    if (!e.fields.Needs) continue
    if (!needs.has(e.fields.Needs)) needs.set(e.fields.Needs, [])
    needs.get(e.fields.Needs).push(e)
  }
  const groups = [...needs].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
  for (const [work, list] of groups) {
    const links = list.map((e) => `[${nodeName(e.file)} ${e.id}](${href(e.file, e)})`).join(", ")
    out.push(`- **${work}** closes ${list.length}: ${links}`)
  }
  const unnamed = gaps.filter((e) => !e.fields.Needs).length
  if (groups.length) out.push("")
  if (unnamed) out.push(`${plural(unnamed, "gap")} ${unnamed === 1 ? "names" : "name"} nothing yet.`, "")
  return out.join("\n")
}

const exists = async (path) => {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

const main = async () => {
  const check = process.argv.includes("--check")
  const names = (await readdir(queueDir)).filter((n) => n.endsWith(".md") && n !== "README.md" && n !== GAPS_FILE).sort()

  const entries = []
  const notes = new Map()
  for (const name of names) {
    const found = parseQueue(await readFile(join(queueDir, name), "utf8"), name)
    const ids = found.map((e) => e.id)
    const dupes = ids.filter((id, i) => ids.indexOf(id) !== i)
    if (dupes.length) console.log(`${name}\n  FAIL ${[...new Set(dupes)].join(", ")} used twice`)
    for (const node of found.flatMap(nodesOf)) {
      if (!notes.has(node)) notes.set(node, await exists(join(vaultDir, `${node}.md`)))
    }
    entries.push(...found)
    if (dupes.length) process.exitCode = 1
  }

  let failures = 0
  const tally = new Map()
  for (const e of entries) {
    const { fails, warns } = lintEntry(e, (node) => notes.get(node))
    for (const fail of fails) console.log(`${e.file} ${e.id}\n  FAIL ${fail}`)
    for (const warn of warns) tally.set(warn, (tally.get(warn) ?? 0) + 1)
    failures += fails.length
  }

  const gaps = renderGaps(entries)
  const path = join(queueDir, GAPS_FILE)
  if (check) {
    const current = (await exists(path)) ? (await readFile(path, "utf8")).replace(/\r\n/g, "\n") : ""
    if (current !== gaps) tally.set(`${GAPS_FILE} is out of date, run npm run queue`, 1)
  } else {
    await writeFile(path, gaps)
  }

  for (const [warn, n] of tally) console.log(`  warn ${warn}${n > 1 ? ` (${n} entries)` : ""}`)
  const warnings = [...tally.values()].reduce((a, b) => a + b, 0)
  console.log(`${plural(entries.length, "queue entry", "queue entries")}, ${plural(failures, "failure")}, ${plural(warnings, "warning")}`)
  if (failures) process.exitCode = 1
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(`\nQueue check failed: ${error.message}`)
    process.exitCode = 1
  })
}
